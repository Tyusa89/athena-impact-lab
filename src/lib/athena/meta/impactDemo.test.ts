import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { SUPPORT_DESK_CATALOG, SUPPORT_DESK_MAPPING, SUPPORT_DESK_PERIODS, SUPPORT_DESK_SOURCE } from "../core/ingest/fixtures";
import { createEvidenceLedger, csvAdapter, importSource } from "../core/ingest";
import { allowAll, identity, trusted } from "../core/ingest/testSupport";
import { createIdentityBoundary, type IdentityVerifier, type VerifiedIdentity } from "../core/identity";
import { SUPPORT_DESK_MODEL } from "../impactModels";
import { runPrototypeImpact } from "./adapter.server";
import { CAUSAL_WORDS, renderImpactMapMarkdown } from "./impact";
import { runImpactAnalysis } from "./runtime";

// docs/business-impact-demo.md is GENERATED from the engine so reviewers read real output. This test fails if the document is stale.
// Regenerate with UPDATE_DOCS=1.
const FILE = "docs/business-impact-demo.md";
const proto = async (roleId: string, question: string, scenarioId = "baseline") => {
  const r = await runPrototypeImpact({ scenarioId, roleId, ownerConfirmed: true, question });
  if (r.state !== "ok") throw new Error(r.reason);
  return renderImpactMapMarkdown(r.impact, question);
};
async function desk(question: string) {
  const ledger = createEvidenceLedger(identity);
  const ctx = trusted("tenant-desk");
  const { readFileSync: read } = await import("node:fs");
  const r = importSource({ identity, ctx, policy: allowAll, adapter: csvAdapter, input: read("src/lib/athena/core/ingest/fixtures/customer-support.csv", "utf8"), source: SUPPORT_DESK_SOURCE, spec: SUPPORT_DESK_MAPPING, catalog: SUPPORT_DESK_CATALOG });
  if (!r.ok) throw new Error("import");
  ledger.commit(ctx, r, "main");
  const verifier: IdentityVerifier = { assurance: "verified", verify: (c) => c as VerifiedIdentity | null };
  const res = await runImpactAnalysis({}, {
    resolve: () => ({ ok: true, credential: { tenantId: "tenant-desk", actorId: "analyst" }, dataset: "main", question }),
    identity: createIdentityBoundary(verifier), allowSimulatedIdentity: false, store: { candidates: (c, d) => ledger.store.candidates(trusted(c.tenantId), d) },
    policy: { evidenceScope: (c) => ({ tenantId: c.tenantId, permits: () => true }) }, analysis: { catalog: SUPPORT_DESK_CATALOG, periods: SUPPORT_DESK_PERIODS }, question: "unused",
  }, SUPPORT_DESK_MODEL, { provenance: (id) => { const p = ledger.provenanceOf(ctx, "main", id); return p ? { batchId: p.batchId, sourceId: p.sourceId, line: p.line } : undefined; } });
  if (res.state !== "ok") throw new Error(res.reason);
  return renderImpactMapMarkdown(res.impact, question);
}

async function build(): Promise<string> {
  const Q1 = "Why is revenue down while lead volume is rising?", Q2 = "Is slower fulfillment hurting sales?", Q3 = "Why is customer satisfaction falling while ticket volume rises?";
  const parts = [
    "# Business Impact Map: generated demonstration",
    "",
    "Generated by the engine from the bundled SYNTHETIC datasets (no model, no network). Regenerate with `UPDATE_DOCS=1 bunx vitest run src/lib/athena/meta/impactDemo`; a test fails if this file is stale.",
    "Read the labels: **verified** items are computed from authorized evidence; **relationships** are verified co-movement, never cause; **hypotheses** are unverified; **actions** need human approval.",
    "",
    "## 1. Multi-department question (business operations, Executive role)", "", await proto("exec", Q1),
    "", "## 2. Operations against Sales (business operations, Executive role)", "", await proto("exec", Q2),
    "", "## 3. Same question where the evidence does not support the story (scenario C: lead quality was flat)", "", await proto("exec", Q1, "ops-only"),
    "", "## 4. The same question as a restricted role (Finance Analyst sees only Finance evidence)", "", await proto("finance", Q1),
    "", "## 5. A different business: customer support (separate catalog, imported from CSV, with import provenance)", "", await desk(Q3),
  ];
  return parts.join("\n") + "\n";
}

describe("generated demonstration document", () => {
  it("is up to date", async () => {
    const now = await build();
    if (process.env["UPDATE_DOCS"] === "1") { writeFileSync(FILE, now); return; }
    expect(existsSync(FILE)).toBe(true);
    expect(readFileSync(FILE, "utf8")).toBe(now);
  });
  it("labels every kind of statement and contains no cause wording", async () => {
    const now = await build();
    for (const h of ["#### Verified changes", "#### Relationships (verified co-movement, not cause)", "#### Hypotheses (UNVERIFIED)", "#### Missing evidence", "#### Proposed actions (require human approval; not executable)"]) expect(now).toContain(h);
    const allowed = now.replace(/\(verified co-movement, not cause\)/g, "").replace(/never cause/g, ""); // the two places the document names the idea in order to deny it
    expect(allowed).not.toMatch(CAUSAL_WORDS);
  });
});
